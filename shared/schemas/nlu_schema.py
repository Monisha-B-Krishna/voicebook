
"""
NLUResult schema - validates structured JSON returned by the NLU layer.
"""

from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field, field_validator


class IntentType(str, Enum):
    BOOKING = "BOOKING"
    PAYMENT = "PAYMENT"
    RETURN = "RETURN"
    QUERY = "QUERY"
    COMPLETE = "COMPLETE"
    CANCEL = "CANCEL"
    UNKNOWN = "UNKNOWN"


class Transaction(BaseModel):
    """One structured transaction extracted from an utterance."""

    intent: IntentType

    customer_name: Optional[str] = Field(
        default=None,
        description="Customer name/nickname as spoken.",
    )

    date: Optional[str] = Field(
        default=None,
        description="Explicit event date in YYYY-MM-DD format.",
    )

    item: Optional[str] = Field(
        default=None,
        description="Item or vessel type mentioned.",
    )

    quantity: Optional[int] = Field(
        default=None,
        description="Number of items booked or returned.",
    )

    amount: Optional[float] = Field(
        default=None,
        description="Money amount mentioned, in INR.",
    )

    payment_type: Optional[str] = Field(
        default=None,
        description="'advance', 'balance', or 'full'.",
    )

    needs_clarification: Optional[str] = Field(
        default=None,
        description="Field requiring clarification before saving.",
    )

    @field_validator("quantity")
    @classmethod
    def quantity_must_be_positive(cls, v):
        if v is not None and v <= 0:
            raise ValueError("quantity must be positive")
        return v

    @field_validator("amount")
    @classmethod
    def amount_must_be_positive(cls, v):
        if v is not None and v < 0:
            raise ValueError("amount cannot be negative")
        return v


class NLUResult(BaseModel):
    """Complete parsed result for one voice utterance."""

    raw_transcript: str = Field(
        description="Original ASR transcript.",
    )

    entry_timestamp: str = Field(
        description="ISO timestamp when the utterance was recorded.",
    )

    transactions: list[Transaction] = Field(
        default_factory=list,
        description="Transactions extracted from the utterance.",
    )

    is_multi_intent: bool = False

    confidence_note: Optional[str] = None

    # Optional context supplied by the application, not generated by NLU.
    booking_id: Optional[int] = Field(
        default=None,
        description="Existing booking reference supplied by the application "
                    "when a follow-up transaction belongs to that booking.",
    )
